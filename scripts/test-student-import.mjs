import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import ts from "typescript";
const source=readFileSync(new URL("../lib/student-import.ts",import.meta.url),"utf8");
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const exports={};
new Function("exports",js)(exports);
const {normalizeChileanRut,isValidChileanRut,validateStudentImport}=exports;
assert.equal(normalizeChileanRut("12.345.678-5"),"12345678-5");
assert.equal(isValidChileanRut("12.345.678-5"),true);
assert.equal(isValidChileanRut("12.345.678-0"),false);
assert.equal(isValidChileanRut("123456789012345"),false);
const good=validateStudentImport([["Ana María","Pérez","Soto","12.345.678-5","4° A"]]);
assert.equal(good.students.length,1);
assert.equal(good.issues.length,0);
const duplicated=validateStudentImport([["Ana","Pérez","Soto","12.345.678-5","4° A"],["Luis","Rojas","Díaz","12345678-5","5° B"]]);
assert.equal(duplicated.students.length,1);
assert.equal(duplicated.issues[0].row,3);
assert.match(duplicated.issues[0].reason,/duplicado/);
const incomplete=validateStudentImport([["Ana","","Soto","12.345.678-5","4° A"]]);
assert.equal(incomplete.students.length,0);
assert.match(incomplete.issues[0].reason,/Faltan/);
console.log("Student import validations: OK");
